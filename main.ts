// main.ts — token launch radar entry point.
//
// Reads the sealed DefiLlama snapshot, ranks the pre-token protocols by the
// implied value of the token they have not launched yet, and writes the full
// hand-in to the output directory:
//   board.json     the ranked board (rows carry their farm plans)
//   dashboard/     the reader-facing dashboard, with data.js generated from
//                  this run's board so the page and the board always agree
//   screenshots/   the dashboard screenshots shipped in the repo
//   dossier.json   the dossier of the above, built by lib/dossier.ts
//
// Usage: node main.ts [--input /input/snapshot.json]
// Output directory: $MAKEFUN_OUTPUT_DIR, else /output.

import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildBoard, type Snapshot } from './lib/model.ts';
import { buildDossier } from './lib/dossier.ts';

const HERE = dirname(fileURLToPath(import.meta.url));

function argValue(flag: string): string | null {
  const args = process.argv.slice(2);
  const at = args.indexOf(flag);
  if (at >= 0 && at + 1 < args.length) return args[at + 1] as string;
  return null;
}

// Recursive copy with entries visited in name order, so a run's outputs do
// not depend on filesystem enumeration order.
function copyTree(from: string, to: string): void {
  mkdirSync(to, { recursive: true });
  const entries = readdirSync(from, { withFileTypes: true }).sort((a, b) =>
    a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
  );
  for (const e of entries) {
    const src = join(from, e.name);
    const dst = join(to, e.name);
    if (e.isDirectory()) copyTree(src, dst);
    else if (e.isFile()) copyFileSync(src, dst);
  }
}

function main(): void {
  const inputPath = argValue('--input') ?? '/input/snapshot.json';
  const outDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

  const snapshot = JSON.parse(readFileSync(inputPath, 'utf8')) as Snapshot;
  const rows = buildBoard(snapshot);

  mkdirSync(outDir, { recursive: true });

  const board = {
    radar: 'token-radar-02',
    as_of: snapshot.as_of,
    source: snapshot.source,
    floor_usd: snapshot.floor_usd,
    model:
      'implied value = TVL x category multiple (median mcap/TVL of the ' +
      'snapshot\'s token-bearing protocols in the category, shrunk toward ' +
      'the global median) x momentum factor (7d TVL change) x maturity ' +
      'factor (days tracked)',
    rows,
  };
  writeFileSync(join(outDir, 'board.json'), JSON.stringify(board, null, 2) + '\n');

  // The dashboard ships in the repo; its data file is generated here so the
  // page renders exactly this run's board.
  copyTree(join(HERE, 'dashboard'), join(outDir, 'dashboard'));
  const dataJs =
    '// Generated by main.ts from this run\'s board. Do not edit by hand.\n' +
    'window.RADAR_DATA = ' +
    JSON.stringify({
      as_of: snapshot.as_of,
      floor_usd: snapshot.floor_usd,
      protocol_count: snapshot.protocols.length,
      watchlist_count: snapshot.watchlist.length,
      rows,
    }) +
    ';\n';
  writeFileSync(join(outDir, 'dashboard', 'data.js'), dataJs);

  copyTree(join(HERE, 'screenshots'), join(outDir, 'screenshots'));

  const dossier = buildDossier(outDir, { text_max_bytes: 65536 });
  writeFileSync(join(outDir, 'dossier.json'), dossier);

  const covered = rows.filter((r) => r.watchlist).length;
  console.log(
    'board rows: ' + rows.length +
      ', watchlist covered: ' + covered + '/' + snapshot.watchlist.length +
      ', top: ' + (rows[0]?.slug ?? 'none') + ' $' + (rows[0]?.implied_value_usd ?? 0),
  );
}

main();
